#!/usr/bin/env python3
"""Generate include/app_icon.h from the APPLaunch app icon.

The help overlay embeds a small RGB565 copy of packaging/applaunch/share/
images/kanstl.png so the binary does not need a PNG decoder or an icon file
at runtime. Run this script after changing the icon artwork.
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "packaging/applaunch/share/images/kanstl.png"
TARGET = ROOT / "include/app_icon.h"
SIZE = 48


def pack(r: int, g: int, b: int) -> int:
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


# Icon pixels darker than this (0-255 luma) become transparent, so the tile
# background blends into the help panel instead of showing as a dark square.
TRANSPARENT_BELOW = 34

# The panel is dimmer than the home-screen icon, so lift it slightly.
GAIN = 1.3


def main() -> None:
    image = Image.open(SOURCE).convert("RGB")
    image = image.resize((SIZE, SIZE), Image.LANCZOS)

    values = []
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b = image.getpixel((x, y))
            luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
            if luma < TRANSPARENT_BELOW:
                values.append(0)
            else:
                values.append(pack(min(255, int(r * GAIN)),
                                   min(255, int(g * GAIN)),
                                   min(255, int(b * GAIN))))

    lines = [
        "// Generated by scripts/gen_icon.py from the APPLaunch app icon.",
        "// Do not edit by hand.",
        "",
        "#ifndef KANSTL_APP_ICON_H",
        "#define KANSTL_APP_ICON_H",
        "",
        "#include <cstdint>",
        "",
        f"constexpr int kAppIconSize = {SIZE};",
        "",
        "static const uint16_t kAppIcon[kAppIconSize * kAppIconSize] = {",
    ]
    for row in range(SIZE):
        chunk = values[row * SIZE:(row + 1) * SIZE]
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in chunk) + ",")
    lines += ["};", "", "#endif  // KANSTL_APP_ICON_H", ""]

    TARGET.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
